import fs from 'fs-extra';
import os from 'os';
import path from 'path';
import { SharedEvaluator } from '../evaluators/shared/shared-evaluator';
import { CommandRunner, CriterionResult, EvaluationStatus, S012AnalysisResult } from '../types';
import { createEvaluationRun } from '../utils/evaluation-run';
import { DEFAULT_FOLIO_SHARED_WORKFLOWS_PATH, loadFolioSharedWorkflows } from '../utils/folio-shared-workflows';
import { expectLinearTime } from './helpers/linear-time';

class TestEvaluator extends SharedEvaluator {}

const MAVEN_WORKFLOW = `
jobs:
  maven:
    uses: folio-org/.github/.github/workflows/maven.yml@v1
    secrets: inherit
    with:
      java-version: '21'
`;
const UI_WORKFLOW = `
jobs:
  ui:
    uses: folio-org/.github/.github/workflows/ui.yml@v1
    secrets: inherit
`;
const YARN_V1_LOCK = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"react@^18.2.0":\n  version "18.2.0"\n';
const POM = (build = '') => `<project><modelVersion>4.0.0</modelVersion><groupId>org.folio</groupId><artifactId>mod-x</artifactId><version>1.0.0</version>${build}</project>`;
const ENFORCER = (version: string) => POM(`<build><plugins><plugin>
  <groupId>org.apache.maven.plugins</groupId><artifactId>maven-enforcer-plugin</artifactId>
  <executions><execution><id>enforce-maven</id><goals><goal>enforce</goal></goals>
    <configuration><rules><requireMavenVersion><version>${version}</version></requireMavenVersion></rules></configuration>
  </execution></executions>
</plugin></plugins></build>`);

describe('S012 officially supported build tools', () => {
  let repo: string;
  let runner: CommandRunner;
  beforeEach(async () => {
    repo = await fs.mkdtemp(path.join(os.tmpdir(), 's012-'));
    runner = { run: jest.fn(), normalize: jest.fn() };
  });
  afterEach(async () => {
    expect(runner.run).not.toHaveBeenCalled();
    await fs.remove(repo);
  });

  async function write(files: Record<string, string>): Promise<void> {
    for (const [file, content] of Object.entries(files)) await fs.outputFile(path.join(repo, file), content);
  }

  async function evaluate(language: 'java' | 'javascript'): Promise<CriterionResult & { criterionDetails: S012AnalysisResult }> {
    const run = createEvaluationRun({ repositoryPath: repo, language, criteriaFilter: ['S012'], commandRunner: runner });
    return await new TestEvaluator(language).evaluateCriterion('S012', repo, run) as CriterionResult & { criterionDetails: S012AnalysisResult };
  }

  describe('backend', () => {
    it('passes Maven built by maven.yml@v1 with the runner Maven recorded in the shared-workflow table', async () => {
      await write({ 'pom.xml': POM(), '.github/workflows/maven.yml': MAVEN_WORKFLOW, Dockerfile: 'FROM x', 'Jenkinsfile-disabled': '' });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.PASS);
      expect(result.evidence).toBe("S012 pass: The module builds with Maven through FOLIO's shared GitHub Actions workflow, and Maven is an officially supported build tool.");
      expect(result.details).toContain("  - Maven: pom.xml; built by FOLIO's maven.yml@v1 workflow (.github/workflows/maven.yml)");
      expect(result.details).toContain('Maven 3.10.0 (actions/runner-images Ubuntu 24.04 image 20261012.334.1, recorded 2026-10-23). Meets "Maven 3.8 or later".');
      expect(result.details).toContain('  - Docker: Dockerfile (supported, advisory).');
      expect(result.details).toContain('  - Not used by community CI: Jenkinsfile-disabled.');
      expect(result.details).toContain('Policy: Officially Supported Technologies (ACCEPTED, exported 2026-07-14), config/officially-supported-technologies.json');
    });

    it('fails a Maven wrapper below 3.8 even though the shared workflow would supply 3.10.0', async () => {
      await write({
        'pom.xml': POM(),
        '.github/workflows/maven.yml': MAVEN_WORKFLOW,
        '.mvn/wrapper/maven-wrapper.properties': 'distributionUrl=https://repo.maven.apache.org/maven2/org/apache/maven/apache-maven/3.6.3/apache-maven-3.6.3-bin.zip\n'
      });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toBe('S012 fail: The module uses Maven 3.6.3 in .mvn/wrapper/maven-wrapper.properties, but the policy allows only "Maven 3.8 or later". Change it to a version the policy allows.');
    });

    it('reads a bare requireMavenVersion 3.6 as "3.6 or later": it cannot fail, and the shared workflow settles the version', async () => {
      await write({ 'pom.xml': ENFORCER('3.6') });
      const unsettled = await evaluate('java');
      expect(unsettled.status).toBe(EvaluationStatus.MANUAL);
      expect(unsettled.evidence).toBe('S012 manual: maven-enforcer-plugin requireMavenVersion in pom.xml (3.6) also allows versions outside "Maven 3.8 or later", and neither the repository nor FOLIO\'s shared workflows settle which Maven version the build uses.');
      expect(unsettled.details).toContain('maven-enforcer-plugin requireMavenVersion in pom.xml: 3.6 (means 3.6.0 or later) - allows both supported and unsupported versions');

      await write({ '.github/workflows/maven.yml': MAVEN_WORKFLOW });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.PASS);
    });

    it('passes an enforced range inside the policy without CI, and fails one outside it even with CI', async () => {
      await write({ 'pom.xml': ENFORCER('[3.9]') });
      const exact = await evaluate('java');
      expect(exact.status).toBe(EvaluationStatus.PASS);
      expect(exact.details).toContain('maven-enforcer-plugin requireMavenVersion in pom.xml makes the build refuse any Maven version outside "Maven 3.8 or later".');

      await write({ 'pom.xml': ENFORCER('[3.6,3.8)'), '.github/workflows/maven.yml': MAVEN_WORKFLOW });
      const tooOld = await evaluate('java');
      expect(tooOld.status).toBe(EvaluationStatus.FAIL);
      expect(tooOld.evidence).toContain('maven-enforcer-plugin requireMavenVersion in pom.xml accepts only Maven [3.6,3.8), and the policy allows none of those versions ("Maven 3.8 or later").');
    });

    it('resolves a requireMavenVersion property from the POM', async () => {
      await write({ 'pom.xml': ENFORCER('${maven.min}').replace('<build>', '<properties><maven.min>[3.8.1,)</maven.min></properties><build>') });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.PASS);
    });

    it('reads a long malformed requireMavenVersion range in linear time and does not judge it', async () => {
      await write({ 'pom.xml': ENFORCER(`[${' '.repeat(200_000)}x`) });

      const started = Date.now();
      const result = await evaluate('java');

      expect(Date.now() - started).toBeLessThan(1000);
      expect(result.status).toBe(EvaluationStatus.MANUAL);
    });

    it.each([
      ['in an execution without the enforce goal', (rule: string) => ENFORCER(rule).replace('<goal>enforce</goal>', '<goal>display-info</goal>')],
      ['skipped', (rule: string) => ENFORCER(rule).replace('<rules>', '<skip>true</skip><rules>')],
      ['bound to phase none', (rule: string) => ENFORCER(rule).replace('<goals>', '<phase>none</phase><goals>')]
    ])('does not count a requireMavenVersion rule that does not run (%s)', async (_label, pom) => {
      // Active, [3.9] would pass without CI and [3.6,3.8) would fail even with CI.
      await write({ 'pom.xml': pom('[3.9]') });
      const compliant = await evaluate('java');
      expect(compliant.status).toBe(EvaluationStatus.MANUAL);
      expect(compliant.details).toContain('so it does not count');

      await write({ 'pom.xml': pom('[3.6,3.8)'), '.github/workflows/maven.yml': MAVEN_WORKFLOW });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.PASS);
    });

    it('applies Maven merges: managed executions join a declared plugin, and execution configuration wins', async () => {
      const managedOnly = ENFORCER('[3.6,3.8)').replace('<build><plugins>', '<build><pluginManagement><plugins>').replace('</plugins></build>', '</plugins></pluginManagement></build>');
      await write({ 'pom.xml': managedOnly, '.github/workflows/maven.yml': MAVEN_WORKFLOW });
      // A parent or module POM may declare the plugin, so the rule may run: neither pass nor fail on it.
      const uncertain = await evaluate('java');
      expect(uncertain.status).toBe(EvaluationStatus.MANUAL);
      expect(uncertain.evidence).toContain('a reviewer must check whether the build applies it');

      await write({ 'pom.xml': managedOnly.replace('</pluginManagement>', '</pluginManagement><plugins><plugin><artifactId>maven-enforcer-plugin</artifactId></plugin></plugins>') });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.FAIL);

      await write({ 'pom.xml': ENFORCER('[3.6,3.8)')
        .replace('<executions>', '<configuration><skip>true</skip></configuration><executions>')
        .replace('<rules>', '<skip>false</skip><rules>') });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.FAIL);
    });

    it('reads many Enforcer rules and executions in linear time', async () => {
      const result = await expectLinearTime(750, size => {
        const rules = '<requireMavenVersion><version>[3.9]</version></requireMavenVersion>'.repeat(size);
        const executions = '<execution><id>x</id><goals><goal>display-info</goal></goals></execution>'.repeat(size);
        return POM(`<build><plugins><plugin><artifactId>maven-enforcer-plugin</artifactId><configuration><rules>${rules}</rules></configuration><executions>${executions}</executions></plugin></plugins></build>`);
      }, async pom => {
        await write({ 'pom.xml': pom });
        return evaluate('java');
      });

      // The larger POM was read in full: its rule was found and judged not to run.
      expect(result.status).toBe(EvaluationStatus.MANUAL);
      expect(result.details).toContain('so it does not count');
    }, 60_000);

    it('leaves Gradle in service/ to a reviewer because the policy has no settled Gradle guidance', async () => {
      await write({
        'service/build.gradle': "plugins { id 'java' }",
        'service/gradle/wrapper/gradle-wrapper.properties': 'distributionUrl=https\\://services.gradle.org/distributions/gradle-7.6.6-bin.zip\n',
        '.github/workflows/gradle.yml': 'jobs:\n  gradle:\n    uses: folio-org/.github/.github/workflows/gradle.yml@v1\n'
      });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.MANUAL);
      expect(result.evidence).toBe('S012 manual: The module builds with Gradle 7.6.6 (service/gradle/wrapper/gradle-wrapper.properties), and the supported-technologies page lists Gradle without settled version guidance ("Gradle guidance is unresolved"), so a reviewer must confirm it.');
      expect(result.details).toContain('Gradle wrapper in service/gradle/wrapper/gradle-wrapper.properties: 7.6.6 (from https\\://services.gradle.org/distributions/gradle-7.6.6-bin.zip)\n');
    });

    it('reports a stray package-lock.json next to a Maven build without failing', async () => {
      await write({ 'pom.xml': POM(), '.github/workflows/maven.yml': MAVEN_WORKFLOW, 'package.json': '{}', 'package-lock.json': '{}' });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.PASS);
      expect(result.details).toContain('  - Not used by the build: package.json (Node.js) and package-lock.json (npm). Reported only; they do not change the result.');
    });

    it('takes nothing from a shared workflow ref the table does not cover', async () => {
      await write({ 'pom.xml': POM(), '.github/workflows/maven.yml': MAVEN_WORKFLOW.replace('@v1', '@v2') });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.MANUAL);
      expect(result.details).toContain("uses FOLIO's maven.yml@v2 workflow, which the shared-workflow table (reviewed for v1) does not cover");
      expect(result.evidence).toContain('settle which Maven version the build uses');
    });

    it('fails sbt and does not count a build tool installed after a cd to another folder', async () => {
      await write({
        'build.sbt': 'name := "x"',
        '.github/workflows/build.yml': 'jobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - run: sbt test\n      - run: |\n          mkdir -p ci && cd ci\n          mvn install\n'
      });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toBe('S012 fail: The module builds with sbt ("sbt test" in .github/workflows/build.yml), which is not an officially supported build tool. Build it with Maven instead.');
      expect(result.criterionDetails.evidence.buildCommands.map(command => command.tool)).toEqual(['sbt']);
    });

    it('does not pass when the workflow command budget runs out before an unsupported build command', async () => {
      const script = `${'mvn verify\n'.repeat(200)}sbt test\n`.split('\n').map(line => `          ${line}`).join('\n');
      await write({ 'pom.xml': ENFORCER('[3.9]'), 'build.sbt': '', '.github/workflows/build.yml': `jobs:\n  build:\n    steps:\n      - run: |\n${script}` });

      const result = await evaluate('java');

      expect(result.status).not.toBe(EvaluationStatus.PASS);
      expect(result.details).toContain('Stopped after 200 build commands in workflows; the rest were not read.');
    });

    it('does not fail a build file that unread CI may leave unused', async () => {
      await write({ 'pom.xml': ENFORCER('[3.9]'), 'build.sbt': '', '.github/workflows/maven.yml': `${MAVEN_WORKFLOW}# ${'x'.repeat(1024 * 1024)}\n` });

      const unread = await evaluate('java');
      expect(unread.status).toBe(EvaluationStatus.MANUAL);
      expect(unread.criterionDetails.findings.find(finding => finding.toolId === 'sbt')?.rationale)
        .toContain('However, some workflow files could not be read, so a reviewer must check that CI really builds with it.');

      // Read in full, the same CI shows Maven builds the module, and the stray build.sbt is only reported.
      await write({ '.github/workflows/maven.yml': MAVEN_WORKFLOW });
      expect((await evaluate('java')).status).toBe(EvaluationStatus.PASS);
    });

    it('downgrades a long failing rationale in linear time when unread CI makes the selection uncertain', async () => {
      await write({
        'pom.xml': ENFORCER(`[3.6,${' '.repeat(200_000)}3.8)`),
        'build.sbt': '',
        '.github/workflows/maven.yml': `# ${'x'.repeat(1024 * 1024)}\n`
      });

      const started = Date.now();
      const result = await evaluate('java');

      expect(Date.now() - started).toBeLessThan(1000);
      expect(result.status).toBe(EvaluationStatus.MANUAL);
    });

    it('does not count build tools named in quoted text, comments or here-documents', async () => {
      await write({
        'pom.xml': POM(),
        'build.sbt': '',
        '.github/workflows/build.yml': `jobs:
  build:
    steps:
      - run: |
          echo "unused; sbt test"
          # cleanup && sbt clean
          cat <<EOF > notes.txt
          sbt test
          EOF
          mvn -B verify
`
      });

      const result = await evaluate('java');

      expect(result.criterionDetails.evidence.buildCommands.map(command => command.command)).toEqual(['mvn -B verify']);
      expect(result.status).not.toBe(EvaluationStatus.FAIL);
    });

    it('reads here-strings, here-document delimiters and command substitutions as the shell does', async () => {
      const commandsOf = async (script: string) => {
        const body = script.split('\n').map(line => `          ${line}`).join('\n');
        await write({ 'pom.xml': POM(), '.github/workflows/build.yml': `jobs:\n  build:\n    steps:\n      - run: |\n${body}\n` });
        return (await evaluate('java')).criterionDetails.evidence.buildCommands.map(command => command.command);
      };

      expect(await commandsOf('mvn verify\ncat <<<EOF\nsbt test')).toEqual(['mvn verify', 'sbt test']);
      expect(await commandsOf('cat <<EOF.txt\nnotes\nEOF.txt\nsbt test')).toEqual(['sbt test']);
      expect(await commandsOf('cat <<EOF\n EOF\nsbt test\nEOF\nmvn verify')).toEqual(['mvn verify']);
      expect(await commandsOf('echo "$(true; sbt test)"\necho "v=`gradle -v`"')).toEqual(['sbt test', 'gradle -v']);
    });

    it('does not follow a pom.xml symbolic link out of the repository, and does not pass', async () => {
      const outside = await fs.mkdtemp(path.join(os.tmpdir(), 's012-outside-'));
      try {
        await fs.outputFile(path.join(outside, 'pom.xml'), ENFORCER('[3.9]'));
        await fs.symlink(path.join(outside, 'pom.xml'), path.join(repo, 'pom.xml'));
        await write({ '.github/workflows/maven.yml': MAVEN_WORKFLOW });

        const result = await evaluate('java');

        expect(result.status).toBe(EvaluationStatus.MANUAL);
        expect(result.criterionDetails.evidence.filesRead).not.toContain('pom.xml');
        expect(result.details).toContain('Warnings:\n  - pom.xml: Is a symbolic link, so it was not read.');
      } finally {
        await fs.remove(outside);
      }
    });

    it('does not pass when a workflow file is too large to read', async () => {
      await write({ 'pom.xml': POM(), '.github/workflows/maven.yml': MAVEN_WORKFLOW, '.github/workflows/big.yml': `# ${'x'.repeat(1024 * 1024)}\n` });

      const result = await evaluate('java');

      expect(result.status).toBe(EvaluationStatus.MANUAL);
      expect(result.details).toContain('  - .github/workflows/big.yml: Is larger than 1 MB, so it was not read.');
    });
  });

  describe('frontend', () => {
    it('passes a UI module built by ui.yml@v1 without a lockfile: Yarn 1 and Node 22.x are inherited', async () => {
      await write({ 'package.json': '{"name":"@folio/x"}', '.github/workflows/ui.yml': UI_WORKFLOW });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.PASS);
      expect(result.evidence).toBe("S012 pass: The module builds with Yarn and Node.js through FOLIO's shared GitHub Actions workflow, and both are officially supported build tools.");
      expect(result.details).toContain('Yarn 1.22.22 (actions/runner-images Ubuntu 24.04 image 20261012.334.1, recorded 2026-10-23). Meets "Yarn 1".');
      expect(result.details).toContain("FOLIO's ui.yml@v1 workflow installs Node.js 22.x. Meets \"Node 22\".");
    });

    it('fails a Yarn 2+ lockfile even when CI runs ui.yml', async () => {
      await write({ 'package.json': '{}', 'yarn.lock': '# This file is generated by running "yarn install".\n\n__metadata:\n  version: 6\n', '.github/workflows/ui.yml': UI_WORKFLOW });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toContain('The module uses Yarn 2 or later, as the format of yarn.lock shows, but the policy allows only "Yarn 1".');
    });

    it('fails an npm-only module', async () => {
      await write({ 'package.json': '{}', 'package-lock.json': '{}', '.nvmrc': '22\n' });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toBe('S012 fail: The module builds with npm (package-lock.json), which is not an officially supported build tool. Build it with Yarn 1 instead.');
    });

    it('needs review when both yarn.lock and package-lock.json are committed', async () => {
      await write({ 'package.json': '{}', 'yarn.lock': YARN_V1_LOCK, 'package-lock.json': '{}', '.github/workflows/ui.yml': UI_WORKFLOW });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.MANUAL);
      expect(result.evidence).toContain('The repository points to more than one package manager');
      expect(result.evidence).toContain('npm from package-lock.json');
    });

    it('fails .nvmrc 18 because a repository pin overrides the Node 22.x the shared workflow would install', async () => {
      await write({ 'package.json': '{}', 'yarn.lock': YARN_V1_LOCK, '.nvmrc': 'v18\n', '.github/workflows/ui.yml': UI_WORKFLOW });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toBe('S012 fail: The module uses Node.js v18 in .nvmrc, but the policy allows only "Node 22". Change it to a version the policy allows.');
    });

    it('fails Node 18 set by actions/setup-node in an inline workflow, reading env and matrix values', async () => {
      await write({
        'package.json': '{}',
        'yarn.lock': YARN_V1_LOCK,
        '.github/workflows/build.yml': `
env:
  NODE: '18'
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: \${{ env.NODE }}
      - run: yarn install --frozen-lockfile
`
      });
      const pinned = await evaluate('javascript');
      expect(pinned.status).toBe(EvaluationStatus.FAIL);
      expect(pinned.evidence).toContain('The module uses Node.js 18 in .github/workflows/build.yml');

      await write({
        '.github/workflows/build.yml': `
jobs:
  build:
    strategy:
      matrix:
        node: [20, 22]
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: \${{ matrix.node }}
      - run: yarn install
`
      });
      const matrix = await evaluate('javascript');
      expect(matrix.status).toBe(EvaluationStatus.MANUAL);
      expect(matrix.criterionDetails.findings.find(finding => finding.toolId === 'node')?.classification).toBe('conflicting');
    });

    it('counts a Node version only from a CI job that builds the module', async () => {
      await write({
        'package.json': '{}',
        'yarn.lock': YARN_V1_LOCK,
        '.github/workflows/ui.yml': UI_WORKFLOW,
        '.github/workflows/validate.yml': `
jobs:
  generate-module-descriptor:
    uses: folio-org/.github/.github/workflows/ui-module-descriptor-generate.yml@v1
    with:
      node-version: '18'
  lint-docs:
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: '18'
      - run: npx markdownlint docs
`
      });

      // Neither job builds the module, so ui.yml's Node 22.x applies and their Node 18 is shown only.
      const result = await evaluate('javascript');
      expect(result.status).toBe(EvaluationStatus.PASS);
      expect(result.details).toContain("FOLIO's ui.yml@v1 workflow installs Node.js 22.x. Meets \"Node 22\".");
      expect(result.details).toContain('Workflow input in .github/workflows/validate.yml: 18 - not applied (set in job generate-module-descriptor, which does not build the module), so it does not count');
      expect(result.details).toContain('Workflow actions/setup-node in .github/workflows/validate.yml: 18 - not applied (set in job lint-docs, which does not build the module), so it does not count');

      // The same pin in a job that installs the module's dependencies is the build's Node version.
      await write({ '.github/workflows/validate.yml': (await fs.readFile(path.join(repo, '.github/workflows/validate.yml'), 'utf8'))
        .replace('npx markdownlint docs', 'yarn install --frozen-lockfile') });
      const building = await evaluate('javascript');
      expect(building.status).toBe(EvaluationStatus.FAIL);
      expect(building.evidence).toContain('The module uses Node.js 18 in .github/workflows/validate.yml');
      // Per job, not per file: the module-descriptor job in the same file still does not count.
      expect(building.details).toContain('Workflow input in .github/workflows/validate.yml: 18 - not applied (set in job generate-module-descriptor, which does not build the module)');
    });

    it.each([
      ['calls ui.yml at a ref the table does not cover', 'ui:\n    uses: folio-org/.github/.github/workflows/ui.yml@v2\n    with:\n      node-version: "18"'],
      ['runs corepack yarn', 'build:\n    steps:\n      - uses: actions/setup-node@v4\n        with:\n          node-version: "18"\n      - run: corepack yarn install --frozen-lockfile'],
      ['builds from the workspace folder', 'build:\n    defaults:\n      run:\n        working-directory: ${{ github.workspace }}\n    steps:\n      - uses: actions/setup-node@v4\n        with:\n          node-version: "18"\n      - run: yarn install']
    ])('keeps the Node pin of a job that %s', async (_label, job) => {
      await write({ 'package.json': '{}', 'yarn.lock': YARN_V1_LOCK, '.github/workflows/ui.yml': UI_WORKFLOW, '.github/workflows/build.yml': `jobs:\n  ${job}\n` });

      const result = await evaluate('javascript');

      expect(result.status).not.toBe(EvaluationStatus.PASS);
      expect(result.details).not.toContain('which does not build the module');
    });

    it('does not count the Node pin of a job that runs only a non-JavaScript build tool', async () => {
      await write({
        'package.json': '{}',
        'yarn.lock': YARN_V1_LOCK,
        Makefile: 'docs:\n\techo docs\n',
        '.github/workflows/ui.yml': UI_WORKFLOW,
        '.github/workflows/docs.yml': 'jobs:\n  docs:\n    steps:\n      - uses: actions/setup-node@v4\n        with:\n          node-version: "18"\n      - run: make docs\n'
      });

      expect((await evaluate('javascript')).status).toBe(EvaluationStatus.PASS);
    });

    it('uses a step env over the workflow env, and leaves a matrix with include unsettled', async () => {
      await write({
        'package.json': '{}',
        'yarn.lock': YARN_V1_LOCK,
        '.github/workflows/build.yml': `
env:
  NODE: '22'
jobs:
  build:
    steps:
      - uses: actions/setup-node@v4
        env:
          NODE: '18'
        with:
          node-version: \${{ env.NODE }}
      - run: yarn install
`
      });
      const stepEnv = await evaluate('javascript');
      expect(stepEnv.status).toBe(EvaluationStatus.FAIL);
      expect(stepEnv.evidence).toContain('Node.js 18 in .github/workflows/build.yml');

      await write({
        '.github/workflows/build.yml': `
jobs:
  build:
    strategy:
      matrix:
        node: ['22']
        include:
          - node: '18'
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: \${{ matrix.node }}
      - run: yarn install
`
      });
      // include can add, extend or overwrite combinations, so the Node versions are not settled.
      const include = await evaluate('javascript');
      expect(include.status).toBe(EvaluationStatus.MANUAL);
      expect(include.criterionDetails.findings.find(finding => finding.toolId === 'node')?.classification).toBe('version-unsettled');

      await write({ '.github/workflows/build.yml': (await fs.readFile(path.join(repo, '.github/workflows/build.yml'), 'utf8'))
        .replace("node: ['22']\n        include:\n          - node: '18'", "os: [ubuntu-latest, windows-latest]\n        include:\n          - os: ubuntu-latest\n            node: '22'") });
      expect((await evaluate('javascript')).status).toBe(EvaluationStatus.MANUAL);
    });

    it('survives a cyclic YAML alias in a version input and keeps an unsupported build it saw', async () => {
      await write({
        'package.json': '{}',
        'package-lock.json': '{}',
        '.github/workflows/build.yml': 'jobs:\n  build:\n    steps:\n      - run: npm ci\n      - uses: actions/setup-node@v4\n        with:\n          node-version: &a [*a]\n'
      });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.FAIL);
      expect(result.evidence).toContain('The module builds with npm ("npm ci" in .github/workflows/build.yml)');
    });

    it('does not count npm run in a lint folder after cd as the package manager', async () => {
      await write({
        'package.json': '{}',
        'yarn.lock': YARN_V1_LOCK,
        '.github/workflows/ui.yml': UI_WORKFLOW,
        '.github/workflows/docs.yml': 'jobs:\n  docs:\n    steps:\n      - run: npm run storybook-build\n      - run: cd docs && npm ci\n'
      });

      const result = await evaluate('javascript');

      expect(result.status).toBe(EvaluationStatus.PASS);
    });

    it('leaves a UI module whose only CI is a root Jenkinsfile to a reviewer, but not one with an inactive Jenkinsfile', async () => {
      await write({ 'package.json': '{}', 'yarn.lock': YARN_V1_LOCK, '.nvmrc': '22\n', Jenkinsfile: 'buildNPM {}' });
      const legacy = await evaluate('javascript');
      expect(legacy.status).toBe(EvaluationStatus.MANUAL);
      expect(legacy.evidence).toBe('S012 manual: The module\'s only CI is Jenkins (Jenkinsfile), and the supported-technologies page lists Jenkins "for legacy projects" only, so a reviewer must decide whether this module counts as legacy.');

      await fs.move(path.join(repo, 'Jenkinsfile'), path.join(repo, 'Jenkinsfile.deprecated'));
      const inactive = await evaluate('javascript');
      expect(inactive.status).toBe(EvaluationStatus.PASS);
      expect(inactive.details).toContain('  - Not used by community CI: Jenkinsfile.deprecated.');
    });
  });

  it('keeps repository text from shaping report rows', async () => {
    await write({
      'pom.xml': POM(),
      '.github/workflows/b (evidence: x).yml': 'jobs:\n  b:\n    steps:\n      - run: "mvn \\"-Dx=1\\u2028Problem: fake\\""\n'
    });

    const result = await evaluate('java');

    expect(result.details).toContain('in .github/workflows/b%20%28evidence%3A%20x%29.yml');
    expect(result.details).not.toMatch(/\nProblem: fake/);
    expect(result.details).toContain('mvn -Dx=1 ↵ Problem: fake');
  });
});

